// Deployment is a row of the deployments table.
type Deployment struct {
	ID                   string
	AppID                string
	Seq                  int
	JobID                string
	Kind                 string
	State                string
	ImageRef             string
	ImageDigest          *string
	ConfigSnapshotJSON   string
	ConfigVersion        int
	StrategyEffective    *string
	HostPort             *int
	ContainerID          *string
	ContainerName        *string
	PreviousDeploymentID *string
	RollbackOfID         *string
	FailureStep          *string
	FailureCode          *string
	FailureMessage       *string
	CreatedAt            time.Time
	StartedAt            *time.Time
	FinishedAt           *time.Time
}

// DeploymentEvent is one timeline row (every step with start,
// end and result).
type DeploymentEvent struct {
	ID     int64
	Step   string
	Status string
	TS     time.Time
	Detail json.RawMessage
}

// CreateDeploymentInput is the write shape for CreateDeployment. Both IDs
// are generated by the caller so the deploy job and its deployment can be
// inserted in one transaction (the job payload references the deployment).
type CreateDeploymentInput struct {
	ID                   string
	AppID                string
	JobID                string
	Kind                 string // deploy | rollback
	ImageRef             string
	ConfigSnapshotJSON   string
	ConfigVersion        int
	PreviousDeploymentID *string
	// RollbackOfID marks this deployment as a rollback of that one.
	RollbackOfID *string
}

// CreateDeployment inserts a pending deployment before the validate step
// runs. The caller wraps it with the deploy job in one transaction.
func (s *Store) CreateDeployment(ctx context.Context, in CreateDeploymentInput) (*Deployment, error) {
	now := time.Now().UTC()
	var seq int
	err := s.db.QueryRowContext(ctx,
		`SELECT COALESCE(MAX(seq), 0) + 1 FROM deployments WHERE app_id = ?`,
		in.AppID).Scan(&seq)
	if err != nil {
		return nil, fmt.Errorf("store: next deployment seq: %w", err)
	}
	var prev any
	if in.PreviousDeploymentID != nil {
		prev = *in.PreviousDeploymentID
	}
	var rollbackOf any
	if in.RollbackOfID != nil {
		rollbackOf = *in.RollbackOfID
	}
	_, err = s.db.ExecContext(ctx, `
		INSERT INTO deployments (id, app_id, seq, job_id, kind, state, image_ref,
		                         config_snapshot_json, config_version,
		                         previous_deployment_id, rollback_of_id, created_at)
		VALUES (?, ?, ?, ?, ?, 'pending', ?, ?, ?, ?, ?, ?)`,
		in.ID, in.AppID, seq, in.JobID, in.Kind, in.ImageRef,
		in.ConfigSnapshotJSON, in.ConfigVersion, prev, rollbackOf, now.UnixMilli())
	if err != nil {
		return nil, fmt.Errorf("store: create deployment: %w", err)
	}
	return s.GetDeployment(ctx, in.ID)
}

// GetDeployment fetches one deployment (ErrNotFound when absent).
func (s *Store) GetDeployment(ctx context.Context, id string) (*Deployment, error) {
	row := s.db.QueryRowContext(ctx, deploymentSelect+` WHERE id = ?`, id)
	d, err := scanDeployment(row)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, ErrNotFound
	}
	return d, err
}

// ListDeployments returns an app's deployment history newest first
func (s *Store) ListDeployments(ctx context.Context, appID string) ([]*Deployment, error) {
	rows, err := s.db.QueryContext(ctx, deploymentSelect+
		` WHERE app_id = ? ORDER BY seq DESC`, appID)
	if err != nil {
		return nil, fmt.Errorf("store: list deployments: %w", err)
	}
	defer rows.Close()
	var out []*Deployment
	for rows.Next() {
		d, err := scanDeployment(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, d)
	}
	return out, rows.Err()
}

const deploymentSelect = `
	SELECT id, app_id, seq, job_id, kind, state, image_ref, image_digest,
	       config_snapshot_json, config_version, strategy_effective, host_port,
	       container_id, container_name, previous_deployment_id, rollback_of_id,
	       failure_step, failure_code, failure_message,
	       created_at, started_at, finished_at
	FROM deployments`

func scanDeployment(row scannable) (*Deployment, error) {
	var (
		d         Deployment
		digest    sql.NullString
		strategy  sql.NullString
		hostPort  sql.NullInt64
		container sql.NullString
		cName     sql.NullString
		prev      sql.NullString
		rollback  sql.NullString
		failStep  sql.NullString
		failCode  sql.NullString
		failMsg   sql.NullString
		createdMS int64
		startedMS sql.NullInt64
		finMS     sql.NullInt64
	)
	err := row.Scan(&d.ID, &d.AppID, &d.Seq, &d.JobID, &d.Kind, &d.State,
		&d.ImageRef, &digest, &d.ConfigSnapshotJSON, &d.ConfigVersion,
		&strategy, &hostPort, &container, &cName, &prev, &rollback,
		&failStep, &failCode, &failMsg, &createdMS, &startedMS, &finMS)
	if err != nil {
		return nil, err
	}
	d.ImageDigest = nullStr(digest)
	d.StrategyEffective = nullStr(strategy)
	if hostPort.Valid {
		p := int(hostPort.Int64)
		d.HostPort = &p
	}
	d.ContainerID = nullStr(container)
	d.ContainerName = nullStr(cName)
	d.PreviousDeploymentID = nullStr(prev)
	d.RollbackOfID = nullStr(rollback)
	d.FailureStep = nullStr(failStep)
	d.FailureCode = nullStr(failCode)
	d.FailureMessage = nullStr(failMsg)
	d.CreatedAt = time.UnixMilli(createdMS).UTC()
	if startedMS.Valid {
		t := time.UnixMilli(startedMS.Int64).UTC()
		d.StartedAt = &t
	}
	if finMS.Valid {
		t := time.UnixMilli(finMS.Int64).UTC()
		d.FinishedAt = &t
	}
	return &d, nil
}

// MarkDeploymentRunning flips pending → running once and stamps started_at.
// Re-running is a no-op.
func (s *Store) MarkDeploymentRunning(ctx context.Context, id string) error {
	res, err := s.db.ExecContext(ctx, `
		UPDATE deployments SET state = 'running', started_at = ?
		WHERE id = ? AND state = 'pending'`, time.Now().UTC().UnixMilli(), id)
	if err != nil {
		return fmt.Errorf("store: mark running: %w", err)
	}
	if n, _ := res.RowsAffected(); n == 0 {
		// Already running (or later): verify the row exists so a typo'd id
		// is still an error.
		if _, err := s.GetDeployment(ctx, id); err != nil {
			return err
		}
	}
	return nil
}

// AllocateHostPort picks a loopback host port from the managed range
// that no active deployment holds and records it in one
// transaction. Returns the existing port if one
// was already allocated (idempotent re-run).
func (s *Store) AllocateHostPort(ctx context.Context, deploymentID string) (int, error) {
	err := s.WithTx(ctx, func(tx *sql.Tx) error {
		var existing sql.NullInt64
		if err := tx.QueryRowContext(ctx,
			`SELECT host_port FROM deployments WHERE id = ?`, deploymentID).
			Scan(&existing); err != nil {
			return fmt.Errorf("store: load deployment port: %w", err)
		}
		if existing.Valid {
			return nil // admission already granted
		}
		rows, err := tx.QueryContext(ctx, `
			SELECT host_port FROM deployments
			WHERE state IN ('pending','running','succeeded')
			  AND host_port IS NOT NULL`)
		if err != nil {
			return fmt.Errorf("store: list used ports: %w", err)
		}
		used := map[int]bool{}
		for rows.Next() {
			var p int
			if err := rows.Scan(&p); err != nil {
				rows.Close()
				return err
			}
			used[p] = true
		}
		rows.Close()
		if err := rows.Err(); err != nil {
			return err
		}

		const (
			minPort = 20000 // policy.MinHostPort, duplicated as SQL literal
			maxPort = 29999 // policy.MaxHostPort
		)
		// Deterministic scan from a random start: spreads ports across the
		// range while still exhausting every candidate before failing.
		start := minPort + rand.Intn(maxPort-minPort+1)
		for i := 0; i <= maxPort-minPort; i++ {
			candidate := minPort + (start-minPort+i)%(maxPort-minPort+1)
			if used[candidate] {
				continue
			}
			res, err := tx.ExecContext(ctx,
				`UPDATE deployments SET host_port = ? WHERE id = ?`,
				candidate, deploymentID)
			if err != nil {
				return fmt.Errorf("store: assign port: %w", err)
			}
			// The unique index on active deployments is the final guard: if
			// a concurrent allocation took this port, try the next one.
			if n, _ := res.RowsAffected(); n == 1 {
				return nil
			}
		}
		return fmt.Errorf("E_NO_FREE_PORT: managed range %d-%d exhausted", minPort, maxPort)
	})
	if err != nil {
		return 0, err
	}
	d, err := s.GetDeployment(ctx, deploymentID)
	if err != nil {
		return 0, err
	}
	if d.HostPort == nil {
		return 0, fmt.Errorf("store: port allocation vanished for %s", deploymentID)
	}
	return *d.HostPort, nil
}

