// FailDeployment marks a deployment failed with the failing step and error
// code. Idempotent: a failed
// deployment keeps its first failure record.
func (s *Store) FailDeployment(ctx context.Context, id, step, code, message string) error {
	_, err := s.db.ExecContext(ctx, `
		UPDATE deployments
		SET state = 'failed', failure_step = ?, failure_code = ?,
		    failure_message = ?, finished_at = ?
		WHERE id = ? AND state IN ('pending','running')`,
		step, code, message, time.Now().UTC().UnixMilli(), id)
	if err != nil {
		return fmt.Errorf("store: fail deployment: %w", err)
	}
	return nil
}

// SucceedDeployment is the finalize step: one transaction that
// flips this deployment to succeeded, supersedes the app's previous current
// deployment, and updates apps.current_deployment_id. Re-running it is
// safe after a crash between commit and job finish.
func (s *Store) SucceedDeployment(ctx context.Context, appID, deploymentID string) error {
	return s.WithTx(ctx, func(tx *sql.Tx) error {
		var prevCurrent sql.NullString
		if err := tx.QueryRowContext(ctx,
			`SELECT current_deployment_id FROM apps WHERE id = ?`, appID).
			Scan(&prevCurrent); err != nil {
			return fmt.Errorf("store: load app for finalize: %w", err)
		}
		if prevCurrent.Valid && prevCurrent.String != deploymentID {
			if _, err := tx.ExecContext(ctx, `
				UPDATE deployments SET state = 'superseded'
				WHERE id = ? AND state IN ('running','succeeded')`,
				prevCurrent.String); err != nil {
				return fmt.Errorf("store: supersede previous: %w", err)
			}
		}
		res, err := tx.ExecContext(ctx, `
			UPDATE deployments
			SET state = 'succeeded', finished_at = ?, failure_step = NULL,
			    failure_code = NULL, failure_message = NULL
			WHERE id = ?`, time.Now().UTC().UnixMilli(), deploymentID)
		if err != nil {
			return fmt.Errorf("store: succeed deployment: %w", err)
		}
		if n, _ := res.RowsAffected(); n == 0 {
			if _, err := tx.ExecContext(ctx, `
				SELECT id FROM deployments WHERE id = ?`, deploymentID); err != nil {
				return err
			}
		}
		if _, err := tx.ExecContext(ctx, `
			UPDATE apps SET current_deployment_id = ?, updated_at = ? WHERE id = ?`,
			deploymentID, time.Now().UTC().UnixMilli(), appID); err != nil {
			return fmt.Errorf("store: set current deployment: %w", err)
		}
		return nil
	})
}

// AppendDeploymentEvent appends one timeline row. detail may be
// nil or any JSON-serializable value.
func (s *Store) AppendDeploymentEvent(ctx context.Context, deploymentID, step, status string, detail any) error {
	var raw []byte
	if detail != nil {
		b, err := json.Marshal(detail)
		if err != nil {
			return fmt.Errorf("store: marshal event detail: %w", err)
		}
		raw = b
	}
	_, err := s.db.ExecContext(ctx, `
		INSERT INTO deployment_events (deployment_id, ts, step, status, detail_json)
		VALUES (?, ?, ?, ?, ?)`,
		deploymentID, time.Now().UTC().UnixMilli(), step, status, nullJSON(raw))
	if err != nil {
		return fmt.Errorf("store: append event: %w", err)
	}
	return nil
}

func nullJSON(b []byte) any {
	if len(b) == 0 {
		return nil
	}
	return string(b)
}

// ListDeploymentEvents returns the timeline in insertion order.
func (s *Store) ListDeploymentEvents(ctx context.Context, deploymentID string) ([]*DeploymentEvent, error) {
	rows, err := s.db.QueryContext(ctx, `
		SELECT id, ts, step, status, detail_json
		FROM deployment_events WHERE deployment_id = ? ORDER BY id`,
		deploymentID)
	if err != nil {
		return nil, fmt.Errorf("store: list events: %w", err)
	}
	defer rows.Close()
	var out []*DeploymentEvent
	for rows.Next() {
		var (
			ev     DeploymentEvent
			tsMS   int64
			detail sql.NullString
		)
		if err := rows.Scan(&ev.ID, &tsMS, &ev.Step, &ev.Status, &detail); err != nil {
			return nil, err
		}
		ev.TS = time.UnixMilli(tsMS).UTC()
		if detail.Valid {
			ev.Detail = json.RawMessage(detail.String)
		}
		out = append(out, &ev)
	}
	return out, rows.Err()
}

// DeploymentOwnsContainer implements the third ownership check:
// the container id must sit on a deployment of this app. Deployment states
// pending/running/succeeded can all legitimately reference a container (a
// failed one may still have a recorded container awaiting cleanup).
func (s *Store) DeploymentOwnsContainer(ctx context.Context, appID, containerID string) (bool, error) {
	var n int
	err := s.db.QueryRowContext(ctx, `
		SELECT COUNT(*) FROM deployments
		WHERE app_id = ? AND container_id = ?`, appID, containerID).Scan(&n)
	if err != nil {
		return false, fmt.Errorf("store: ownership lookup: %w", err)
	}
	return n > 0, nil
}

