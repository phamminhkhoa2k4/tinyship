// AppendAudit writes an append-only audit row (the audit_events table
// has triggers that make it immutable). Used for ownership refusals,
// admission force and other security-relevant decisions.
func (s *Store) AppendAudit(ctx context.Context, actor, action, targetType, targetID, result string, detail any) error {
	var raw []byte
	if detail != nil {
		b, err := json.Marshal(detail)
		if err != nil {
			return fmt.Errorf("store: marshal audit detail: %w", err)
		}
		raw = b
	}
	_, err := s.db.ExecContext(ctx, `
		INSERT INTO audit_events (ts, actor, action, target_type, target_id, result, detail_json)
		VALUES (?, ?, ?, ?, ?, ?, ?)`,
		time.Now().UTC().UnixMilli(), actor, action, targetType, targetID, result, nullJSON(raw))
	if err != nil {
		return fmt.Errorf("store: append audit: %w", err)
	}
	return nil
}

// CountAuditEvents returns how many audit rows match action+target. It
// exists so security refusals are observable from outside the
// store package: the worker's log-server tests and, later, audit tooling.
func (s *Store) CountAuditEvents(ctx context.Context, action, targetID string) (int, error) {
	var n int
	err := s.db.QueryRowContext(ctx,
		`SELECT COUNT(*) FROM audit_events WHERE action = ? AND target_id = ?`,
		action, targetID).Scan(&n)
	if err != nil {
		return 0, fmt.Errorf("store: count audit: %w", err)
	}
	return n, nil
}
